export const getFilteredDestinations = ({
  priceRange,
  selectedCategories,
  selectedRatings,
  selectedLocations,
  sortOption
}: {
  priceRange: [number, number];
  selectedCategories: string[];
  selectedRatings: number[];
  selectedLocations: string[];
  sortOption: string;
}) => {
  let filtered = [...destinations];

  // Filter by price range
  filtered = filtered.filter(
    (dest) => dest.price >= priceRange[0] && dest.price <= priceRange[1]
  );

  // Filter by category
  if (selectedCategories.length > 0) {
    filtered = filtered.filter((dest) => selectedCategories.includes(dest.category));
  }

  // Filter by rating
  if (selectedRatings.length > 0) {
    filtered = filtered.filter((dest) => {
      return selectedRatings.some((rating) => dest.rating >= rating);
    });
  }

  // Filter by location
  if (selectedLocations.length > 0) {
    filtered = filtered.filter((dest) => {
      const destState = dest.location.split(', ')[1] || dest.location;
      return selectedLocations.some((loc) => destState.includes(loc));
    });
  }

  // Sort destinations
  switch (sortOption) {
    case 'price-low':
      filtered.sort((a, b) => a.price - b.price);
      break;
    case 'price-high':
      filtered.sort((a, b) => b.price - a.price);
      break;
    case 'rating':
      filtered.sort((a, b) => b.rating - a.rating);
      break;
    case 'newest':
      // For this example, we'll just reverse the order as a mockup
      filtered.reverse();
      break;
    default:
      // 'recommended' - no special sorting for now
      break;
  }

  return filtered;
};
